        public static string Lang = Detect();

        static string Detect()
        {
            string forced = (Environment.GetEnvironmentVariable("CLAUDE_TOGETHER_LANG") ?? "").Trim().ToLowerInvariant();
            if (forced == "en" || forced == "tr") return forced;
            return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "tr" ? "tr" : "en";
        }

        /// <summary>Translates <paramref name="en"/> and applies string.Format when arguments are given.</summary>
        public static string T(string en, params object[] args)
        {
            string text = en;
            string tr;
            if (Lang == "tr" && Turkish.TryGetValue(en, out tr)) text = tr;
            return args.Length > 0 ? string.Format(text, args) : text;
        }

